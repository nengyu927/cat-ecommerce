const { chromium } = require('playwright')
const assert = require('node:assert/strict')
async function main() {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const context = await browser.newContext()
    const front = await context.newPage(), admin = await context.newPage()
    const failures = []
    context.on('response', response => {
      if (/^\/(api|admin-api)\//.test(new URL(response.url()).pathname) && response.status() >= 500)
        failures.push(`${response.status()} ${response.url()}`)
    })
    context.on('page', page => page.on('pageerror', e => failures.push(e.message)))
    front.on('pageerror', e => failures.push(e.message)); admin.on('pageerror', e => failures.push(e.message))
    await context.route(url => !['127.0.0.1', 'localhost'].includes(url.hostname), route => route.abort())
    const frontBase = 'http://127.0.0.1:5173', adminBase = 'http://127.0.0.1:5174'
    await front.goto(frontBase + '/login')
    assert.equal(await front.getByRole('link', { name: '後台登入', exact: true }).count(), 0)
    await front.getByRole('button', { name: '一鍵登入會員（展示用）', exact: true }).click()
    await front.waitForURL(frontBase + '/')
    assert.equal(await front.evaluate(() => JSON.parse(localStorage.getItem('catshop_member')).role), 'CUSTOMER')
    const frontCookie = (await context.cookies()).find(c => c.name === 'catshop_refresh' && c.path === '/api/auth')
    assert.ok(frontCookie?.httpOnly)
    await admin.goto(adminBase + '/')
    await admin.waitForURL(url => url.pathname === '/login')
    assert.equal(await admin.getByRole('link', { name: '所有商品', exact: true }).count(), 0)
    assert.equal(await admin.getByRole('link', { name: '購物車', exact: false }).count(), 0)
    await admin.getByRole('button', { name: '一鍵登入管理員（展示用）', exact: true }).click()
    await admin.waitForURL(adminBase + '/products')
    await admin.getByRole('heading', { name: '商品管理', exact: true }).waitFor()
    assert.equal(await admin.evaluate(() => JSON.parse(localStorage.getItem('catshop_member')).role), 'ADMIN')
    assert.equal(await front.evaluate(() => JSON.parse(localStorage.getItem('catshop_member')).role), 'CUSTOMER')
    const cookies = await context.cookies()
    assert.equal(cookies.find(c => c.name === 'catshop_refresh' && c.path === '/api/auth').value, frontCookie.value)
    assert.ok(cookies.find(c => c.name === 'catshop_refresh' && c.path === '/admin-api/auth')?.httpOnly)
    async function expireAndRefresh(page, base, target, expectedRole, apiPath) {
      await page.evaluate(() => {
        const session = JSON.parse(localStorage.getItem('catshop_session'))
        session.token = 'expired-test-access'
        localStorage.setItem('catshop_token', session.token)
        localStorage.setItem('catshop_session', JSON.stringify(session))
      })
      const refreshed = page.waitForResponse(r => new URL(r.url()).pathname === apiPath + '/auth/refresh')
      await page.goto(base + target)
      assert.equal((await refreshed).status(), 200)
      await page.waitForFunction(role => JSON.parse(localStorage.getItem('catshop_member'))?.role === role
        && localStorage.getItem('catshop_token') !== 'expired-test-access', expectedRole)
    }
    await expireAndRefresh(front, frontBase, '/account', 'CUSTOMER', '/api')
    await expireAndRefresh(admin, adminBase, '/orders', 'ADMIN', '/admin-api')
    await admin.getByRole('heading', { name: '訂單管理', exact: true }).waitFor()
    const adminLogout = admin.waitForResponse(r => new URL(r.url()).pathname === '/admin-api/auth/logout')
    await admin.getByRole('button', { name: '登出', exact: true }).click()
    assert.equal((await adminLogout).status(), 200)
    await admin.waitForURL(adminBase + '/login')
    await expireAndRefresh(front, frontBase, '/account', 'CUSTOMER', '/api')
    await front.goto(frontBase + '/admin/products')
    assert.equal(await front.getByRole('heading', { name: '商品管理', exact: true }).count(), 0)
    await admin.goto(adminBase + '/cart')
    assert.equal(await admin.getByRole('heading', { name: '購物車', exact: true }).count(), 0)
    await admin.goto(adminBase + '/login')
    await admin.getByLabel('電子郵件', { exact: true }).fill('customer@catshop.local')
    await admin.getByLabel('密碼', { exact: true }).fill('password123')
    await admin.getByRole('button', { name: '登入', exact: true }).click()
    await admin.getByText('此帳號沒有管理員權限，請使用管理員帳號登入', { exact: true }).waitFor()
    assert.equal(await front.evaluate(() => JSON.parse(localStorage.getItem('catshop_member')).role), 'CUSTOMER')
    assert.deepEqual(failures, [])
    console.log('PASS SPLIT: separate routes/layouts, simultaneous roles, isolated HttpOnly refresh cookies, independent refresh/logout, customer admin rejection; no API 500 or page errors.')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
